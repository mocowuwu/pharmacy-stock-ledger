export const messages: Record<Locale, Record<MessageKey, string>> = { id, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const table = messages[locale] ?? messages.id;
  return (key, vars) => {
    const text = table[key] ?? messages.id[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/gu, (m, name: string) =>
      name in vars ? String(vars[name]) : m,
    );
  };
}

/** For a key built at run time from data (a drug class, a payment method). */
export function hasKey(key: string): key is MessageKey {
  return key in id;
}
